// DevRelay Cloud host agent — core (docs/hosting.md §Host agent API).
//
// This is the ONLY executor of customer code on the hosting VPS: it clones Git
// sources, builds container images with hard caps, runs one container per app
// under the rootless Docker daemon, and owns the on-demand-TLS allow-list plus
// the Caddy routing file. Plain Node (no runtime dependencies) so it runs
// comfortably on the 1 GB box.
//
// Honesty rules, mirroring the DevRelay API side:
// - POST /deployments is idempotent by deploymentId: re-POSTing returns the
//   deployment's current state. Worker retries after an ambiguous timeout read
//   reality instead of guessing.
// - A failed redeploy never stops the previously live container: the new image
//   is built first; only a successful build switches containers, and a failed
//   post-switch probe rolls back to the previous image.
// - Every definite failure carries `error` (<=240 chars) and `logTail`
//   (<=20000 chars). Nothing is ever reported `live` before the container
//   actually answered HTTP on its published loopback port.
//
// Everything here is driven through injected dependencies (exec, fs, probe) so
// the whole state machine is testable without Docker; agent/index.mjs wires
// the real implementations.

import { createHash, timingSafeEqual } from 'node:crypto';

const MAX_ERROR = 240;
const MAX_LOG_TAIL = 20_000;
const RESERVED_SLUGS = new Set(['agent', 'hello', 'www', 'api', 'app', 'admin', 'mail', 'smtp', 'pop', 'ftp']);
const ID_RE = /^[A-Za-z0-9_-]{6,64}$/;
const SLUG_RE = /^[a-z0-9](?:[a-z0-9-]{0,28}[a-z0-9])$/;
const BRANCH_RE = /^[^~^:?*[\s\\]+$/;
const DOMAIN_CHAR_RE = /^[a-z0-9.-]+$/;

export function clip(value, max) {
  const s = String(value ?? '');
  return s.length <= max ? s : s.slice(-max);
}

export function clipHead(value, max) {
  const s = String(value ?? '');
  return s.length <= max ? s : s.slice(0, max);
}

export function validateDeployInput(body, env) {
  if (!body || typeof body !== 'object' || Array.isArray(body)) return { ok: false, error: 'body must be a JSON object' };
  const required = ['deploymentId', 'appId', 'slug', 'name', 'repoUrl', 'branch', 'builder', 'plan', 'memoryMb', 'cpuMilli'];
  for (const key of required) {
    if (body[key] === undefined || body[key] === null || body[key] === '') return { ok: false, error: `missing field: ${key}` };
  }
  for (const key of ['deploymentId', 'appId']) {
    if (typeof body[key] !== 'string' || !ID_RE.test(body[key])) return { ok: false, error: `invalid ${key}` };
  }
  if (typeof body.slug !== 'string' || !SLUG_RE.test(body.slug)) return { ok: false, error: 'slug must be 2-30 chars of a-z0-9 with inner hyphens' };
  if (RESERVED_SLUGS.has(body.slug)) return { ok: false, error: `slug "${body.slug}" is reserved` };
  if (typeof body.name !== 'string' || body.name.length < 1 || body.name.length > 80) return { ok: false, error: 'name must be 1-80 chars' };
  if (typeof body.repoUrl !== 'string') return { ok: false, error: 'repoUrl must be a string' };
  let repoUrl;
  try { repoUrl = new URL(body.repoUrl); } catch { return { ok: false, error: 'repoUrl is not a valid URL' }; }
  if (repoUrl.protocol === 'file:') {
    if (!env.allowFileClones) return { ok: false, error: 'repoUrl must be an https:// Git URL' };
  } else if (repoUrl.protocol !== 'https:') {
    return { ok: false, error: 'repoUrl must be an https:// Git URL' };
  }
  if (typeof body.branch !== 'string' || body.branch.length < 1 || body.branch.length > 100 || !BRANCH_RE.test(body.branch)) {
    return { ok: false, error: 'invalid branch' };
  }
  if (body.builder !== 'dockerfile' && body.builder !== 'node') return { ok: false, error: 'builder must be "dockerfile" or "node"' };
  if (typeof body.plan !== 'string' || body.plan.length < 1 || body.plan.length > 40) return { ok: false, error: 'invalid plan' };
  for (const key of ['memoryMb', 'cpuMilli']) {
    const n = body[key];
    if (!Number.isInteger(n)) return { ok: false, error: `${key} must be an integer` };
  }
  if (body.memoryMb < 64 || body.memoryMb > 1024) return { ok: false, error: 'memoryMb must be 64..1024 on this host' };
  if (body.cpuMilli < 50 || body.cpuMilli > 1000) return { ok: false, error: 'cpuMilli must be 50..1000 on this host' };
  if (body.repoToken !== undefined && (typeof body.repoToken !== 'string' || body.repoToken.length > 500)) {
    return { ok: false, error: 'invalid repoToken' };
  }
  return { ok: true, value: {
    deploymentId: body.deploymentId, appId: body.appId, slug: body.slug, name: body.name,
    repoUrl: body.repoUrl, repoToken: typeof body.repoToken === 'string' ? body.repoToken : undefined,
    branch: body.branch, builder: body.builder, plan: body.plan, memoryMb: body.memoryMb, cpuMilli: body.cpuMilli,
  } };
}

export function generateCaddyfile(env, apps) {
  const sites = [];
  sites.push('# Generated by the DevRelay host agent — do not edit by hand.');
  sites.push(`{
\ton_demand_tls {
\t\task http://127.0.0.1:${env.askPort}
\t}
}`);
  sites.push(`${env.agentHost} {
\ttls {
\t\ton_demand
\t}
\treverse_proxy 127.0.0.1:${env.apiPort}
}`);
  for (const route of env.staticRoutes) {
    sites.push(`${route.host} {
\ttls {
\t\ton_demand
\t}
\treverse_proxy ${route.upstream}
}`);
  }
  for (const app of apps) {
    sites.push(`${app.domain} {
\ttls {
\t\ton_demand
\t}
\treverse_proxy 127.0.0.1:${app.port}
}`);
  }
  sites.push(`*.${env.baseDomain} {
\ttls {
\t\ton_demand
\t}
\trespond "Nothing is deployed at this address." 404
}`);
  return sites.join('\n\n') + '\n';
}

/** Constant-time bearer-token comparison (compares SHA-256 digests). */
export function tokenOk(presented, expected) {
  if (typeof presented !== 'string' || presented.length === 0 || typeof expected !== 'string' || expected.length === 0) return false;
  const a = createHash('sha256').update(presented).digest();
  const b = createHash('sha256').update(expected).digest();
  return timingSafeEqual(a, b);
}

function nodeDockerfile() {
  return [
    'FROM node:22-alpine',
    'WORKDIR /app',
    'ENV NODE_ENV=production PORT=3000',
    'COPY package*.json ./',
    'RUN if [ -f package-lock.json ]; then npm ci --no-audit --no-fund; else npm install --no-audit --no-fund; fi',
    'COPY . .',
    'RUN npm run build --if-present && npm prune --omit=dev',
    'EXPOSE 3000',
    'CMD ["npm", "start"]',
    '',
  ].join('\n');
}

const DEFAULT_ENV = {
  token: '', apiPort: 8787, askPort: 5577, baseDomain: 'apps.devrelay.africa',
  agentHost: 'agent.apps.devrelay.africa', staticRoutes: [],
  dataDir: '/home/devrelay/devrelay-agent', statePath: '/home/devrelay/devrelay-agent/state.json',
  caddyConfigPath: '/var/lib/devrelay/Caddyfile',
  capacityMemoryMb: 768, allowFileClones: false,
  caddyBin: '/usr/local/bin/caddy',
  buildMemoryMb: 768, buildCpuMilli: 900,
  cloneTimeoutMs: 300_000, buildTimeoutMs: 900_000, cmdTimeoutMs: 120_000,
  probeTimeoutMs: 45_000, rollbackProbeTimeoutMs: 30_000,
  containerPrefix: 'dr-', portRangeStart: 10000, portRangeEnd: 10999,
};

export function createAgent(deps) {
  const { exec, fs, probe } = deps;
  const env = { ...DEFAULT_ENV, ...deps.env };
  const log = deps.logger ?? { info: () => {}, warn: () => {}, error: () => {} };
  const now = deps.now ?? (() => new Date().toISOString());

  let state = { version: 1, apps: {}, deployments: {} };
  const queue = [];
  const pendingActions = [];
  let loopPromise = null;

  const persist = () => {
    const tmp = `${env.statePath}.tmp`;
    fs.mkdirSync(env.dataDir, { recursive: true });
    // repoToken never touches disk: the in-memory copy is enough for the one
    // build it belongs to, and interrupted builds are failed at boot anyway.
    const json = JSON.stringify(state, (key, value) =>
      (key === 'repoToken' && typeof value === 'string' && value) ? '[redacted]' : value);
    fs.writeFileSync(tmp, json);
    try { fs.chmodSync?.(tmp, 0o600); } catch { /* best effort (test fakes lack chmod) */ }
    fs.renameSync(tmp, env.statePath);
  };
  const save = () => { try { persist(); } catch (e) { log.error(`state persist failed: ${e?.message ?? e}`); } };

  const appList = () => Object.values(state.apps);
  const allowedDomains = () => new Set([env.agentHost, ...env.staticRoutes.map(r => r.host), ...appList().map(a => a.domain)]);

  // ---------- request handling ----------

  const respond = (status, json) => ({ status, json });

  function requireAuth(headers) {
    const header = headers?.authorization ?? headers?.Authorization;
    if (typeof header !== 'string' || !header.startsWith('Bearer ')) return false;
    return tokenOk(header.slice('Bearer '.length).trim(), env.token);
  }

  function deploymentPublic(d) {
    const out = { status: d.status };
    if (d.url) out.url = d.url;
    if (d.containerRef) out.containerRef = d.containerRef;
    if (d.error) out.error = d.error;
    if (d.status === 'failed' && d.logTail) out.logTail = d.logTail;
    return out;
  }

  const appBusy = (appId) => Object.values(state.deployments).some(d => d.appId === appId && d.status === 'building');

  async function handleApiRequest({ method, path, headers, body }) {
    if (method === 'GET' && path === '/healthz') return respond(200, { ok: true });
    if (!requireAuth(headers)) return respond(401, { error: 'unauthorized' });

    const segments = path.split('/').filter(Boolean).map(s => {
      try { return decodeURIComponent(s); } catch { return s; }
    });

    if (segments[0] === 'deployments') {
      if (method === 'POST' && segments.length === 1) return postDeployment(body);
      if (method === 'GET' && segments.length === 2) {
        const d = state.deployments[segments[1]];
        return d ? respond(200, deploymentPublic(d)) : respond(404, { error: 'deployment not found' });
      }
      return respond(404, { error: 'not found' });
    }

    if (segments[0] === 'apps' && segments.length >= 2) {
      const appId = segments[1];
      const app = state.apps[appId];
      const sub = segments[2];
      if (!app) return respond(404, { error: 'app not found' });
      // All app actions run on the same single-slot queue as builds so a
      // container mutation can never race a deploy's container switch.
      if (method === 'POST' && sub === 'stop') {
        if (appBusy(appId)) return respond(409, { error: 'a build is in progress for this app' });
        return requestAppAction(appId, 'stop');
      }
      if (method === 'POST' && sub === 'start') {
        if (appBusy(appId)) return respond(409, { error: 'a build is in progress for this app' });
        return requestAppAction(appId, 'start');
      }
      if (method === 'DELETE' && segments.length === 2) {
        if (appBusy(appId)) return respond(409, { error: 'a build is in progress for this app' });
        return requestAppAction(appId, 'delete');
      }
      if (method === 'GET' && sub === 'logs') return requestAppAction(appId, 'logs');
      return respond(405, { error: 'method not allowed' });
    }
    return respond(404, { error: 'not found' });
  }

  function postDeployment(body) {
    const check = validateDeployInput(body, env);
    if (!check.ok) return respond(400, { error: check.error });
    const input = check.value;

    // Idempotency: an existing deploymentId answers with its real state —
    // never a second build of the same id.
    const existing = state.deployments[input.deploymentId];
    if (existing) return respond(200, deploymentPublic(existing));

    let app = state.apps[input.appId];
    if (!app) {
      const slugOwner = appList().find(a => a.slug === input.slug);
      if (slugOwner) return respond(409, { error: `slug "${input.slug}" is already used by another app` });
      const used = appList().reduce((sum, a) => sum + (a.memoryMb ?? 0), 0);
      if (used + input.memoryMb > env.capacityMemoryMb) {
        return respond(409, { error: `host at capacity: ${used}m of ${env.capacityMemoryMb}m already allocated` });
      }
      let port;
      try { port = allocatePort(); } catch (e) { return respond(409, { error: e.message }); }
      app = {
        appId: input.appId, slug: input.slug, name: input.name, domain: `${input.slug}.${env.baseDomain}`,
        port, container: `${env.containerPrefix}${input.appId}`, currentImage: null, previousImage: null,
        memoryMb: input.memoryMb, cpuMilli: input.cpuMilli, status: 'building', createdAt: now(),
      };
      state.apps[app.appId] = app;
      log.info(`registered app ${app.appId} (${app.domain}) on 127.0.0.1:${app.port}`);
    } else {
      if (app.slug !== input.slug) return respond(409, { error: 'slug is immutable for an existing app' });
      if (appBusy(app.appId)) return respond(409, { error: 'a build is already in progress for this app' });
      app.memoryMb = input.memoryMb;
      app.cpuMilli = input.cpuMilli;
    }

    const deployment = {
      deploymentId: input.deploymentId, appId: input.appId, status: 'building',
      input, createdAt: now(), buildLog: '',
    };
    state.deployments[input.deploymentId] = deployment;
    save();
    writeRouting();
    enqueue(input.deploymentId);
    log.info(`deployment ${input.deploymentId} queued for app ${input.appId}`);
    return respond(200, deploymentPublic(deployment));
  }

  function allocatePort() {
    const used = new Set(appList().map(a => a.port));
    for (let p = env.portRangeStart; p <= env.portRangeEnd; p++) {
      if (!used.has(p)) return p;
    }
    throw new Error('no free ports in the agent port range');
  }

  // ---------- app actions (executed on the queue, see runPendingActions) ----------

  function requestAppAction(appId, action) {
    return new Promise((resolve) => {
      pendingActions.push({ appId, action, resolve });
      if (!loopPromise) loopPromise = loop();
    });
  }

  async function performStop(app) {
    if (!app.container) { app.status = 'stopped'; return; }
    const r = await exec('docker', ['stop', '-t', '10', app.container], { timeoutMs: env.cmdTimeoutMs });
    if (r.code !== 0 && !/No such container/i.test(r.stderr)) {
      throw new Error(clipHead(`docker stop failed: ${r.stderr}`, MAX_ERROR));
    }
    app.status = 'stopped';
  }

  async function performStart(app) {
    if (!app.container || !app.currentImage) throw new Error('app container does not exist; deploy again');
    const r = await exec('docker', ['start', app.container], { timeoutMs: env.cmdTimeoutMs });
    if (r.code !== 0) throw new Error(clipHead(`docker start failed: ${r.stderr}`, MAX_ERROR));
    app.status = 'live';
  }

  async function performDelete(app) {
    if (app.container) {
      await exec('docker', ['rm', '-f', app.container], { timeoutMs: env.cmdTimeoutMs });
    }
    const images = await exec('docker', ['images', '--format', '{{.Repository}}:{{.Tag}}',
      '--filter', `reference=${env.containerPrefix}${app.appId}:*`], { timeoutMs: env.cmdTimeoutMs });
    for (const tag of images.stdout.split(/\s+/).filter(Boolean)) {
      await exec('docker', ['rmi', '-f', tag], { timeoutMs: env.cmdTimeoutMs });
    }
    delete state.apps[app.appId];
    for (const [id, d] of Object.entries(state.deployments)) {
      if (d.appId === app.appId) delete state.deployments[id];
    }
    save();
    writeRouting();
    await reloadCaddy();
  }

  async function performLogs(app) {
    if (!app.container) return '';
    const r = await exec('docker', ['logs', '--tail', '500', app.container], { timeoutMs: env.cmdTimeoutMs });
    return clip(`${r.stdout}${r.stderr}`, MAX_LOG_TAIL);
  }

  // ---------- ask endpoint (on-demand TLS permission) ----------

  function handleAskRequest({ url }) {
    let params;
    try { params = new URL(url, 'http://127.0.0.1').searchParams; } catch { return 404; }
    const values = params.getAll('domain');
    if (values.length !== 1) return 404;
    const name = values[0];
    if (name.length < 3 || name.length > 253 || !DOMAIN_CHAR_RE.test(name) || name.includes('..')) return 404;
    return allowedDomains().has(name) ? 200 : 404;
  }

  // ---------- routing (Caddy) ----------

  function writeRouting() {
    const content = generateCaddyfile(env, appList());
    const tmp = `${env.caddyConfigPath}.tmp`;
    fs.writeFileSync(tmp, content);
    fs.renameSync(tmp, env.caddyConfigPath);
  }

  async function reloadCaddy() {
    const r = await exec(env.caddyBin, ['reload', '--config', env.caddyConfigPath], { timeoutMs: env.cmdTimeoutMs });
    if (r.code !== 0) log.warn(`caddy reload failed (previous routing stays active): ${clip(r.stderr, 300)}`);
    else log.info('caddy reloaded');
  }

  // ---------- the single-slot queue ----------

  function enqueue(deploymentId) {
    queue.push(deploymentId);
    if (!loopPromise) loopPromise = loop();
  }

  function drain() { return loopPromise ?? Promise.resolve(); }

  async function loop() {
    try {
      // Both work sources are re-checked after every await: a deployment or an
      // app action can arrive while the loop sits between steps, and anything
      // left behind here would hang its caller forever (requestAppAction's
      // promise only resolves when a loop pass picks the action up).
      while (queue.length || pendingActions.length) {
        while (queue.length) {
          const id = queue.shift();
          try { await runDeployment(id); } catch (e) {
            log.error(`deployment ${id} crashed the worker step: ${e?.stack ?? e}`);
            const d = state.deployments[id];
            if (d && d.status === 'building') {
              d.status = 'failed';
              d.error = clipHead(`agent error: ${e?.message ?? e}`, MAX_ERROR);
              const app = state.apps[d.appId];
              if (app && app.status === 'building') app.status = app.currentImage ? 'live' : 'failed';
              save();
            }
          }
        }
        await runPendingActions();
      }
    } finally {
      loopPromise = null;
    }
  }

  async function runPendingActions() {
    while (pendingActions.length) {
      const job = pendingActions.shift();
      const app = state.apps[job.appId];
      try {
        if (!app) { job.resolve(respond(404, { error: 'app not found' })); continue; }
        if (job.action === 'stop') { await performStop(app); save(); job.resolve(respond(200, { ok: true })); }
        else if (job.action === 'start') { await performStart(app); save(); job.resolve(respond(200, { ok: true })); }
        else if (job.action === 'delete') { await performDelete(app); job.resolve(respond(200, { ok: true })); }
        else if (job.action === 'logs') { job.resolve(respond(200, { tail: await performLogs(app) })); }
        else job.resolve(respond(400, { error: 'unknown action' }));
      } catch (e) {
        log.warn(`app action ${job.action} for ${job.appId} failed: ${e?.message ?? e}`);
        job.resolve(respond(409, { error: clipHead(String(e?.message ?? e), MAX_ERROR) }));
      }
    }
  }

  // ---------- deployment pipeline ----------

  const capture = (d, stream) => { d.buildLog = clip(`${d.buildLog ?? ''}\n${stream}`, 400_000); };

  async function failDeployment(deploymentId, error, logTail) {
    const d = state.deployments[deploymentId];
    d.status = 'failed';
    d.error = clipHead(error, MAX_ERROR);
    if (logTail) d.logTail = clip(logTail, MAX_LOG_TAIL);
    d.finishedAt = now();
    const app = state.apps[d.appId];
    if (app && app.status === 'building') app.status = app.currentImage ? 'live' : 'failed';
    save();
  }

  async function runDeployment(deploymentId) {
    const d = state.deployments[deploymentId];
    if (!d || d.status !== 'building') return;
    const app = state.apps[d.appId];
    if (!app) { await failDeployment(deploymentId, 'app vanished from agent state'); return; }
    const input = d.input;
    const dir = `${env.dataDir}/builds/${deploymentId}`;
    try { fs.rmSync(dir, { recursive: true, force: true }); } catch { /* best effort */ }
    fs.mkdirSync(dir, { recursive: true });

    // 1. clone (repoToken is injected git-style; never logged)
    const cloneUrl = input.repoToken && input.repoUrl.startsWith('https://')
      ? input.repoUrl.replace('https://', `https://x-access-token:${input.repoToken}@`)
      : input.repoUrl;
    let r = await exec('git', ['clone', '--depth', '1', '--branch', input.branch, cloneUrl, dir],
      { timeoutMs: env.cloneTimeoutMs, cwd: env.dataDir });
    capture(d, `${r.stdout}\n${r.stderr}`);
    if (r.code !== 0) {
      await failDeployment(deploymentId, `git clone failed: ${lastMeaningful(r.stderr || r.stdout) || `exit ${r.code}`}`, d.buildLog);
      return;
    }

    // 2. builder preparation
    if (input.builder === 'dockerfile') {
      if (!fs.existsSync(`${dir}/Dockerfile`)) {
        await failDeployment(deploymentId, 'builder=dockerfile but the repo has no Dockerfile', d.buildLog);
        return;
      }
    } else {
      let pkg = null;
      try { pkg = JSON.parse(fs.readFileSync(`${dir}/package.json`, 'utf8')); } catch {
        await failDeployment(deploymentId, 'builder=node but the repo has no readable package.json', d.buildLog);
        return;
      }
      if (!pkg?.scripts?.start) {
        await failDeployment(deploymentId, 'package.json has no "start" script (builder=node)', d.buildLog);
        return;
      }
      fs.writeFileSync(`${dir}/Dockerfile`, nodeDockerfile());
    }
    if (!fs.existsSync(`${dir}/.dockerignore`)) {
      fs.writeFileSync(`${dir}/.dockerignore`, '.git\nnode_modules\n');
    }

    // 3. build — the previously live container is untouched during this phase.
    const image = `${env.containerPrefix}${d.appId}:${deploymentId}`;
    r = await exec('docker', ['build', '--progress', 'plain',
      '--memory', `${env.buildMemoryMb}m`, '--cpu-quota', String(env.buildCpuMilli * 100),
      '-t', image, dir], { timeoutMs: env.buildTimeoutMs, cwd: env.dataDir });
    capture(d, `${r.stdout}\n${r.stderr}`);
    if (r.code !== 0) {
      await failDeployment(deploymentId, r.timedOut
        ? `docker build timed out after ${Math.round(env.buildTimeoutMs / 1000)}s`
        : `docker build failed: ${lastMeaningful(r.stderr || r.stdout)}`, d.buildLog);
      return;
    }

    // 4. container port (dockerfile builder: EXPOSE, default 3000; node: 3000)
    let containerPort = 3000;
    if (input.builder === 'dockerfile') {
      const inspect = await exec('docker', ['image', 'inspect', '-f',
        '{{range $p, $_ := .Config.ExposedPorts}}{{$p}} {{end}}', image], { timeoutMs: env.cmdTimeoutMs });
      const m = inspect.stdout.match(/(\d+)\/tcp/);
      if (m) containerPort = Number(m[1]);
    }

    // 5. switch containers (brief stop-start deploy, as documented for v1)
    const previousImage = app.currentImage;
    const hadContainer = Boolean(app.container);
    if (hadContainer) await exec('docker', ['rm', '-f', app.container], { timeoutMs: env.cmdTimeoutMs });
    r = await exec('docker', runArgs(app.container, image, app.port, containerPort, app.memoryMb, app.cpuMilli),
      { timeoutMs: env.cmdTimeoutMs, cwd: env.dataDir });
    capture(d, `${r.stdout}\n${r.stderr}`);
    if (r.code !== 0) {
      if (previousImage && hadContainer) {
        await exec('docker', runArgs(app.container, previousImage, app.port, containerPort, app.memoryMb, app.cpuMilli),
          { timeoutMs: env.cmdTimeoutMs });
        app.currentImage = previousImage;
        app.status = 'live';
      } else {
        app.currentImage = null;
        app.container = null;
        app.status = 'failed';
      }
      await failDeployment(deploymentId, `docker run failed: ${lastMeaningful(r.stderr || r.stdout)}`, d.buildLog);
      return;
    }
    app.container = `${env.containerPrefix}${d.appId}`;

    // 6. honest probe: "live" only once the container answers HTTP
    const answered = await probe(app.port, env.probeTimeoutMs);
    if (!answered.ok) {
      const logs = await performLogs(app);
      await exec('docker', ['rm', '-f', app.container], { timeoutMs: env.cmdTimeoutMs });
      if (previousImage && hadContainer) {
        const back = await exec('docker', runArgs(app.container, previousImage, app.port, containerPort, app.memoryMb, app.cpuMilli),
          { timeoutMs: env.cmdTimeoutMs });
        const oldAnswered = back.code === 0 ? await probe(app.port, env.rollbackProbeTimeoutMs) : { ok: false };
        app.currentImage = previousImage;
        app.status = oldAnswered.ok ? 'live' : 'failed';
        await failDeployment(deploymentId,
          `new container never answered HTTP on 127.0.0.1:${app.port} within ${Math.round(env.probeTimeoutMs / 1000)}s — rolled back to the previous image (app ${app.status})`,
          logs);
        return;
      }
      app.currentImage = null;
      app.container = null;
      app.status = 'failed';
      await failDeployment(deploymentId,
        `container never answered HTTP on 127.0.0.1:${app.port} within ${Math.round(env.probeTimeoutMs / 1000)}s`, logs);
      return;
    }

    // 7. success
    app.currentImage = image;
    app.previousImage = previousImage ?? app.previousImage ?? null;
    app.status = 'live';
    d.status = 'live';
    d.url = `https://${app.domain}`;
    d.containerRef = app.container;
    d.finishedAt = now();
    delete d.error;
    save();
    await reloadCaddy();
    try { fs.rmSync(dir, { recursive: true, force: true }); } catch { /* best effort */ }
    await pruneImages(d.appId, [image, app.previousImage].filter(Boolean));
    log.info(`deployment ${deploymentId} live at ${d.url}`);
  }

  async function pruneImages(appId, keep) {
    const keepSet = new Set(keep);
    const r = await exec('docker', ['images', '--format', '{{.Repository}}:{{.Tag}}',
      '--filter', `reference=${env.containerPrefix}${appId}:*`], { timeoutMs: env.cmdTimeoutMs });
    for (const tag of r.stdout.split(/\s+/).filter(Boolean)) {
      if (!keepSet.has(tag)) await exec('docker', ['rmi', '-f', tag], { timeoutMs: env.cmdTimeoutMs });
    }
  }

  function runArgs(container, image, port, containerPort, memoryMb, cpuMilli) {
    return ['run', '-d', '--name', container, '--restart', 'unless-stopped',
      '--read-only', '--tmpfs', '/tmp:rw,noexec,nosuid,size=64m',
      '-p', `127.0.0.1:${port}:${containerPort}`,
      '--env', `PORT=${containerPort}`,
      '--memory', `${memoryMb}m`, '--memory-swap', `${memoryMb}m`,
      '--cpus', (cpuMilli / 1000).toFixed(3), '--pids-limit', '256',
      image];
  }

  function lastMeaningful(text) {
    const lines = String(text ?? '').split('\n').map(l => l.trim()).filter(Boolean);
    return lines.slice(-3).join(' | ').slice(0, MAX_ERROR);
  }

  // ---------- boot ----------

  async function boot() {
    try {
      state = JSON.parse(fs.readFileSync(env.statePath, 'utf8'));
      state.apps ??= {};
      state.deployments ??= {};
    } catch { state = { version: 1, apps: {}, deployments: {} }; }

    // Reconcile container reality (e.g. after a reboot): rootless docker with
    // --restart unless-stopped brings customer containers back up on its own.
    const ps = await exec('docker', ['ps', '-a', '--format', '{{.Names}}\t{{.Status}}'], { timeoutMs: env.cmdTimeoutMs });
    if (ps.code === 0) {
      const containerStatus = new Map();
      for (const line of ps.stdout.split('\n')) {
        const [name, status] = line.split('\t');
        if (name) containerStatus.set(name, status ?? '');
      }
      for (const app of appList()) {
        const status = containerStatus.get(app.container ?? '');
        if (status === undefined) app.status = 'failed'; // container is gone
        else if (status.startsWith('Up')) app.status = 'live';
        else app.status = 'stopped';
      }
    } else {
      log.warn('docker ps failed at boot; app statuses left as persisted');
    }

    // Interrupted builds are honestly failed: the worker re-POSTs and the user
    // sees the truth, never a stale "building" forever.
    for (const d of Object.values(state.deployments)) {
      if (d.status === 'building') {
        d.status = 'failed';
        d.error = 'agent restarted while this deployment was building; submit a new deployment';
        d.finishedAt = now();
        const app = state.apps[d.appId];
        if (app && app.status === 'building') app.status = app.currentImage ? 'live' : 'failed';
      }
    }
    save();
    writeRouting();
    await reloadCaddy();
    log.info(`agent booted: ${appList().length} app(s), ${Object.keys(state.deployments).length} deployment(s)`);
  }

  return {
    handleApiRequest,
    handleAskRequest,
    requestAppAction,
    drain,
    boot,
    writeRouting,
    reloadCaddy,
    get state() { return state; },
    env,
  };
}
